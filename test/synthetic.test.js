import { describe, it, expect } from "vitest";
import { makeSyntheticSankeyData, addTotalizingNodes } from "../src/data/synthetic.js";
import { energySpec, energySumNodes } from "../src/data/energy.js";

/** @param {any[]} links */
const nodeKeys = (links) =>
  [...new Set(links.flatMap((l) => [l.source, l.target]))].sort();

describe("makeSyntheticSankeyData", () => {
  it("is deterministic for a given seed", () => {
    const opts = { randomSeed: 0.42, regularity: 0.1, optionalProbability: 0.7 };
    const a = makeSyntheticSankeyData(energySpec, opts);
    const b = makeSyntheticSankeyData(energySpec, opts);
    expect(a).toEqual(b);
  });

  it("produces different data for different seeds", () => {
    const a = makeSyntheticSankeyData(energySpec, { randomSeed: 0.1 });
    const b = makeSyntheticSankeyData(energySpec, { randomSeed: 0.9 });
    expect(a).not.toEqual(b);
  });

  it("conserves flow through every intermediate node", () => {
    const links = makeSyntheticSankeyData(energySpec, {
      randomSeed: 0.3,
      regularity: 0.1
    });
    /** @type {Map<string, number>} */
    const inflow = new Map();
    /** @type {Map<string, number>} */
    const outflow = new Map();
    for (const l of links) {
      outflow.set(l.source, (outflow.get(l.source) ?? 0) + l.value);
      inflow.set(l.target, (inflow.get(l.target) ?? 0) + l.value);
    }
    // Nodes listed in `sources` are seeded with a share of `sourceTotal`, so
    // their outflow exceeds their inflow by that share. Only nodes that merely
    // pass flow through must balance exactly — which, in this specification,
    // means excluding those that are both a source and an import target.
    const seeded = new Set(energySpec.sources);
    let checked = 0;
    for (const key of nodeKeys(links)) {
      if (seeded.has(key)) continue;
      const i = inflow.get(key);
      const o = outflow.get(key);
      if (i !== undefined && o !== undefined) {
        expect(o, key).toBeCloseTo(i, 6);
        checked++;
      }
    }
    expect(checked).toBeGreaterThan(0);
  });

  it("emits only positive, finite flows", () => {
    const links = makeSyntheticSankeyData(energySpec, { randomSeed: 0.77 });
    for (const l of links) {
      expect(Number.isFinite(l.value)).toBe(true);
      expect(l.value).toBeGreaterThan(0);
    }
  });

  it("is acyclic", () => {
    const links = makeSyntheticSankeyData(energySpec, { randomSeed: 0.2 });
    /** @type {Map<string, string[]>} */
    const adj = new Map();
    for (const l of links) adj.set(l.source, [...(adj.get(l.source) ?? []), l.target]);
    const state = new Map();
    /** @param {string} n */
    const visit = (n) => {
      if (state.get(n) === 1) return true; // back edge
      if (state.get(n) === 2) return false;
      state.set(n, 1);
      for (const m of adj.get(n) ?? []) if (visit(m)) return true;
      state.set(n, 2);
      return false;
    };
    expect(nodeKeys(links).some(visit)).toBe(false);
  });

  describe("optionalProbability", () => {
    // This is a trap worth pinning down. The inclusion test is
    // `random() >= optionalProbability` and random() returns a value in
    // [0, 1), so at exactly 1 no optional node is ever dropped. Datasets
    // generated by varying only the seed then share one topology and differ
    // only in magnitudes — which is not what "datasets varying in the number
    // of energy sources" means.
    it("keeps every optional node at a probability of 1, whatever the seed", () => {
      const topologies = new Set();
      for (let i = 0; i < 10; i++) {
        const links = makeSyntheticSankeyData(energySpec, {
          randomSeed: i / 10,
          regularity: 0.1,
          optionalProbability: 1
        });
        topologies.add(nodeKeys(links).join(","));
      }
      expect(topologies.size).toBe(1);
    });

    it("varies topology below 1", () => {
      const topologies = new Set();
      for (let i = 0; i < 10; i++) {
        const links = makeSyntheticSankeyData(energySpec, {
          randomSeed: i / 10,
          regularity: 0.1,
          optionalProbability: 0.7
        });
        topologies.add(nodeKeys(links).join(","));
      }
      expect(topologies.size).toBeGreaterThan(1);
    });
  });

  it("makes splits more even as regularity rises", () => {
    /** @param {number} regularity */
    const spread = (regularity) => {
      const links = makeSyntheticSankeyData(energySpec, {
        randomSeed: 0.5,
        regularity
      });
      const sourceLinks = links.filter((l) => l.source === "Imp.");
      const values = sourceLinks.map((l) => l.value);
      const mean = values.reduce((a, b) => a + b, 0) / values.length;
      return Math.sqrt(
        values.reduce((a, v) => a + (v - mean) ** 2, 0) / values.length
      ) / mean;
    };
    expect(spread(0.9)).toBeLessThan(spread(0));
  });
});

describe("addTotalizingNodes", () => {
  it("splits bundled links in two and records the true endpoints", () => {
    const links = makeSyntheticSankeyData(energySpec, { randomSeed: 0.5 });
    const out = addTotalizingNodes(links, energySumNodes);
    expect(out.length).toBeGreaterThan(links.length);

    const intoSum = out.filter((l) => l.target === "Primary energy");
    const outOfSum = out.filter((l) => l.source === "Primary energy");
    expect(intoSum.length).toBeGreaterThan(0);
    expect(intoSum.length).toBe(outOfSum.length);
    for (const l of intoSum) expect(l.trueTarget).toBeDefined();
    for (const l of outOfSum) expect(l.trueSource).toBeDefined();
  });

  it("conserves total flow through each totalizing node", () => {
    const links = makeSyntheticSankeyData(energySpec, { randomSeed: 0.5 });
    const out = addTotalizingNodes(links, energySumNodes);
    for (const key of ["Primary energy", "Total consumption"]) {
      const into = out.filter((l) => l.target === key).reduce((a, b) => a + b.value, 0);
      const outOf = out.filter((l) => l.source === key).reduce((a, b) => a + b.value, 0);
      expect(outOf).toBeCloseTo(into, 6);
    }
  });

  it("leaves unbundled links untouched", () => {
    const links = makeSyntheticSankeyData(energySpec, { randomSeed: 0.5 });
    const out = addTotalizingNodes(links, energySumNodes);
    const exports = links.filter((l) => l.target === "Exp.");
    for (const l of exports) expect(out).toContainEqual(l);
  });
});

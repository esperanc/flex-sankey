/**
 * Seedable pseudo-random number generation.
 *
 * The layout pipeline is randomised in two places: the simulated-annealing
 * node swaps in the ordering stage, and the synthetic data generator. In the
 * original notebooks the ordering stage called `Math.random` and `d3.shuffle`
 * directly, which meant that running the same optimisation twice on the same
 * input could produce different numbers of crossings. That makes published
 * measurements impossible to reproduce exactly.
 *
 * Every randomised entry point in this library therefore accepts a `random`
 * option — a function returning a value in `[0, 1)`. It defaults to
 * `Math.random`, preserving the notebooks' behaviour; pass `randomLcg(seed)`
 * to make a run reproducible.
 *
 * @module internal/random
 *
 * SPDX-License-Identifier: MIT
 * Copyright (c) 2026 Claudio Esperança and contributors
 */

const MUL = 0x19660d;
const INC = 0x3c6ef35f;
const EPS = 1 / 0x100000000;

/**
 * A source of uniform random numbers in `[0, 1)`.
 * @typedef {() => number} RandomSource
 */

/**
 * Creates a seeded linear congruential generator.
 *
 * Reproduces `d3.randomLcg` exactly, so datasets generated here match those
 * generated by the original notebooks for the same seed.
 *
 * @param {number} [seed] Seed. Values in `[0, 1)` are scaled into the full
 *   32-bit state; others are truncated to an integer.
 * @returns {RandomSource}
 */
export function randomLcg(seed = Math.random()) {
  let state = (0 <= seed && seed < 1 ? seed / EPS : Math.abs(seed)) | 0;
  return () => ((state = (MUL * state + INC) | 0), EPS * (state >>> 0));
}

/**
 * Shuffles an array in place, using the Fisher-Yates algorithm.
 *
 * Matches `d3.shuffle`'s traversal order, so a given random source produces
 * the same permutation here as it would there.
 *
 * @template T
 * @param {T[]} array Array to shuffle. Modified in place.
 * @param {RandomSource} [random] Defaults to `Math.random`.
 * @returns {T[]} `array`
 */
export function shuffle(array, random = Math.random) {
  let m = array.length;
  while (m) {
    const i = (random() * m--) | 0;
    const t = array[m];
    array[m] = array[i];
    array[i] = t;
  }
  return array;
}

/**
 * Builds the integer sequence `[start, stop)`.
 *
 * @param {number} start
 * @param {number} [stop] If omitted, the range is `[0, start)`.
 * @returns {number[]}
 */
export function range(start, stop) {
  if (stop === undefined) {
    stop = start;
    start = 0;
  }
  const out = [];
  for (let i = start; i < stop; i++) out.push(i);
  return out;
}

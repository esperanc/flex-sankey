/**
 * Regenerates every benchmark dataset from the manifest.
 *
 * Writes one JSON file per dataset to `benchmarks/datasets/`, plus a summary
 * table. Both are committed: the manifest makes the suite reproducible, the
 * committed output makes it auditable without running anything.
 *
 * Usage: `npm run bench:data`
 *
 * SPDX-License-Identifier: MIT
 * Copyright (c) 2026 Claudio Esperança and contributors
 */

import { writeFileSync, mkdirSync, readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { makeSyntheticSankeyData } from "../src/data/synthetic.js";
import { sankeyLayers, sankeyAddDummies, sankeyOrderNodes } from "../src/layout/index.js";
import { randomLcg } from "../src/internal/random.js";
import { suites, OPTIONAL_PROBABILITY, REGULARITY } from "./manifest.js";

const here = dirname(fileURLToPath(import.meta.url));
const outDir = join(here, "datasets");
const realDir = join(here, "real");

/**
 * Reads a published `source,target,value` CSV.
 *
 * Deliberately minimal: the files under `real/` are kept byte-for-byte as
 * published, and this parser handles exactly the shape they have. Values are
 * split from the right so node names containing a comma survive.
 *
 * @param {string} file Name of a CSV under `benchmarks/real/`.
 * @returns {{source: string, target: string, value: number}[]}
 */
function readRealLinks(file) {
  const text = readFileSync(join(realDir, file), "utf8").trim();
  const [header, ...lines] = text.split(/\r?\n/);
  if (header.trim() !== "source,target,value") {
    throw new Error(`${file}: expected a source,target,value header`);
  }
  return lines.map((line, i) => {
    const v = line.lastIndexOf(",");
    const t = line.lastIndexOf(",", v - 1);
    if (v < 0 || t < 0) throw new Error(`${file}: malformed line ${i + 2}`);
    const value = Number(line.slice(v + 1));
    if (!Number.isFinite(value)) throw new Error(`${file}: bad value on line ${i + 2}`);
    return { source: line.slice(0, t), target: line.slice(t + 1, v), value };
  });
}

/** Seed for the ordering pass used only to report a crossing count. */
const PROBE_SEED = 1;

/**
 * Measures a dataset's shape.
 * @param {any[]} links
 */
function describe(links) {
  const nodeKeys = new Set(links.flatMap((l) => [l.source, l.target]));
  const layout = sankeyAddDummies(sankeyLayers({ links }));
  const ordered = sankeyOrderNodes(layout, {
    nsteps: 40,
    random: randomLcg(PROBE_SEED)
  });
  return {
    nodes: nodeKeys.size,
    links: links.length,
    layers: layout.layers.length,
    dummies: layout.layers.flat().filter((n) => n.dummy).length,
    crossings: ordered.crossings,
    topology: [...nodeKeys].sort().join(",")
  };
}

mkdirSync(outDir, { recursive: true });

/** @type {any[]} */
const summary = [];

for (const suite of suites) {
  const topologies = new Set();
  for (const entry of suite.datasets) {
    const links = entry.file
      ? readRealLinks(entry.file)
      : makeSyntheticSankeyData(/** @type {any} */ (suite.spec), {
          randomSeed: /** @type {number} */ (entry.randomSeed),
          regularity: /** @type {number} */ (entry.regularity),
          optionalProbability: /** @type {number} */ (entry.optionalProbability)
        });
    const shape = describe(links);
    topologies.add(shape.topology);

    writeFileSync(
      join(outDir, `${entry.id}.json`),
      JSON.stringify({ suite: suite.id, ...entry, links }, null, 2) + "\n"
    );

    const { topology, ...reported } = shape;
    summary.push({ suite: suite.id, id: entry.id, ...reported });
  }
  console.log(
    `${suite.id}: ${suite.datasets.length} datasets, ` +
      `${topologies.size} distinct topologies`
  );
}

writeFileSync(join(outDir, "summary.json"), JSON.stringify(summary, null, 2) + "\n");

// A markdown table, ready to drop into the paper — this is the dataset
// description reviewers asked for and the submission did not have.
const cols = ["id", "nodes", "links", "layers", "dummies", "crossings"];
const md = [
  "| " + cols.join(" | ") + " |",
  "| " + cols.map(() => "---").join(" | ") + " |",
  ...summary.map((r) => "| " + cols.map((c) => r[c]).join(" | ") + " |")
].join("\n");
writeFileSync(
  join(outDir, "summary.md"),
  `# Benchmark datasets\n\nGenerated by \`npm run bench:data\`. ` +
    `Regularity ${REGULARITY}, optional probability ${OPTIONAL_PROBABILITY}.\n\n` +
    `Crossings are measured after 40 ordering passes with a fixed seed, ` +
    `as an indication of difficulty only.\n\n${md}\n`
);

console.log(`\nwrote ${summary.length} datasets to benchmarks/datasets/`);
